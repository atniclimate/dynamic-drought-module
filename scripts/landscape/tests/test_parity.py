"""Parity tests: two baselines, one delta contract (WORKPLAN T-M0-1 + T-M0-2).

fixtures/legacy/ is the IMMUTABLE monolith baseline: MANIFEST.json records
its sha256 set and capture provenance, the manifest ITSELF is pinned here by
a hardcoded sha256 (EXPECTED_MANIFEST_SHA256), and TestBaselineImmutability
fails if either is edited. A legitimate rebaseline therefore requires
editing this test file, which makes it a visible, reviewable act.

fixtures/corrected/ is the pinned CURRENT behavior (regenerated by
fixtures/capture_corrected.py at each intentional fix): the live package
must reproduce it BYTE-for-byte here. DeltaManifestEnforcement then closes
the loop against legacy/: the observed legacy-vs-corrected diff must equal,
occurrence by occurrence (file, JSON pointer, change kind, exact values on
both sides), the pins hand-committed in fixtures/delta-manifest.json, and
each pinned field carries a written reason. An unintended behavior change
therefore fails twice: against the corrected bytes, and, if corrected/ were
quietly regenerated to hide it, against the value pins in the manifest
(which only a deliberate, reviewed manifest edit can move).
"""
