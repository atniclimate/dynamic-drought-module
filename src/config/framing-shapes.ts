/**
 * Authored framing minimap shapes for the desktop S4b shell, promoted
 * from the verified 2026-08-04 design kit.
 *
 * PROVENANCE (D-0.7.0-051): ATNI-authored editorial geometry for camera
 * navigation; an owned simplification, not an authoritative boundary of
 * any kind. The runtime clips these masks to Natural Earth 1:50m physical
 * land for coastline presentation only. Coarser than Environmental
 * Protection Agency (EPA) Omernik Level I. Every consumer must carry this
 * labeling.
 *
 * VERIFICATION: the original shared mainland divides retain the edge-matched
 * topology verified in the 2026-08-04 S4 shell kit. Southern Mexico and the
 * disconnected island pieces added for continental coverage are pinned by
 * repository extent and source-mask regression tests.
 *
 * CONVENTION: polygon vertices are [longitude, latitude] (GeoJSON axis
 * order) so the SVG projection and any GeoJSON export stay conventional.
 * Camera BOUNDS elsewhere in the repo remain Leaflet-ordered
 * [[south, west], [north, east]]; only FramingDef.bounds carries that
 * order, never these rings. The rendering projection is the trivial
 * equirectangular the ratified spike prototype used.
 *
 * Region fills belong in src/config/palette.ts (DDM-owned palette
 * doctrine), never inline here; lake cutouts render
 * pointer-transparent; Hawaii renders as the ratified enlarged inset
 * whose click fits REGIONS.hawaii, so it has island blobs, not a ring.
 */

/** [longitude, latitude] */
export type LonLat = readonly [number, number];

/** The eight mainland framing polygons (Hawaii is an inset, below). */
export type MainlandFramingKey =
  | 'alaska-northwest'
  | 'boreal-arctic'
  | 'pacific-coast'
  | 'arid-west'
  | 'plains-prairies'
  | 'eastern-forests'
  | 'southeast-gulf'
  | 'mexico';

/** Country codes used by NCEI's companion North America land mask. */
export type NadmCountryCode = 'US' | 'CA' | 'MX';

/** A sampling area may be broader than the drawn editorial silhouette, but
 * the NCEI land mask and this country allowlist still decide which land is
 * eligible. The area itself is never rendered as jurisdictional geometry. */
